namespace DataControls.Core.Sql;

/// <summary>Safe SQL Server identifier quoting. Identifiers only ever come from the catalog or the engine itself.</summary>
public static class SqlIdentifier
{
    private const int MaxLength = 128;

    /// <summary>[name] with any ']' doubled - the identifier can never break out of its brackets.</summary>
    public static string Quote(string name)
    {
        if (string.IsNullOrEmpty(name) || name.Length > MaxLength || name.Any(char.IsControl))
        {
            throw new ArgumentException($"Invalid SQL identifier '{name}'.", nameof(name));
        }

        return $"[{name.Replace("]", "]]", StringComparison.Ordinal)}]";
    }

    /// <summary>Table aliases are generated by the planner (r, j1, x1_j2); anything else is a programming error.</summary>
    public static string Alias(string alias)
    {
        if (string.IsNullOrEmpty(alias) || !char.IsAsciiLetterLower(alias[0]) || !alias.All(c => char.IsAsciiLetterLower(c) || char.IsAsciiDigit(c) || c == '_'))
        {
            throw new ArgumentException($"Invalid table alias '{alias}'.", nameof(alias));
        }

        return alias;
    }
}
